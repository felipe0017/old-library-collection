// VECTOR 2D OF BINFIX

struct VEC2B{
	BINFIX X,Y;
};

// RETURN A VEC2B OBJECT, USEFULL FOR FUNCTION VEC2B PARAMETERS
VEC2B MAKEV2B(BINFIX X, BINFIX Y){
	VEC2B V;
	V.X = X;
	V.Y = Y;
	return V;
}

VEC2B MAKEV2B(BINFIX D){
	VEC2B V;
	V.X = D;
	V.Y = D;
	return V;
}

VEC2B V2B_ZERO  = MAKEV2B(BF_ZERO);
VEC2B V2B_ONE   = MAKEV2B(BF_ONE);

VEC2B V2B_RIGHT = MAKEV2B(BF_ONE   , BF_ZERO  );
VEC2B V2B_UP    = MAKEV2B(BF_ZERO  , BF_ONE   );
VEC2B V2B_LEFT  = MAKEV2B(BF_NEGONE, BF_ZERO  );
VEC2B V2B_DOWN  = MAKEV2B(BF_ZERO  , BF_NEGONE);

VEC2B V2B_UNDEF = MAKEV2B(BF_UNDEF);


VEC2B INVERSE(VEC2B V){
	VEC2B R;
	R.X = INVSIGN(V.X);
	R.Y = INVSIGN(V.Y);
	return R;
}

VEC2B ABS(VEC2B V){
	VEC2B R;
	R.X = ABS(V.X);
	R.Y = ABS(V.Y);
	return R;
}

VEC2B HALF(VEC2B V){
	VEC2B R;
	R.X = RSHIFT(V.X, 1);
	R.Y = RSHIFT(V.Y, 1);
	return R;
}

VEC2B ADD(VEC2B A, VEC2B B){
	VEC2B R;
	R.X = ADD(A.X, B.X);
	R.Y = ADD(A.Y, B.Y);
	return R;
}

