VEC2B DIV(VEC2B A, VEC2B B){
	VEC2B R;
	R.X = DIV(A.X, B.X);
	R.Y = DIV(A.Y, B.Y);
	return R;
}

VEC2B IDIV(VEC2B A, BINFIX B){
	VEC2B R;
	BINFIX INVB;
	INVB = INV(B);
	R.X = MUL(A.X, INVB);
	R.Y = MUL(A.Y, INVB);
	return R;
}

BINFIX DIST(VEC2B A, VEC2B B){
	BINFIX X = SUB(A.X, B.X);
	BINFIX Y = SUB(A.Y, B.Y);
	BINFIX R;
	R = HYPOT(X, Y);
	return R;
}

BINFIX DIST(VEC2B A){
	return DIST(A, V2B_ZERO);
}

VEC2B NORMALIZE(VEC2B V){
	VEC2B R;
	BINFIX D;
	D = DIST(V);
	R = IDIV(V, D);
	return R;
}

bool ISEQUAL(VEC2B V, VEC2B V1){
	return ISEQUAL(V.X, V1.X) and ISEQUAL(V.Y, V1.Y);
}

// PARA OBTENER LA OTRA DIRECCION DEL VECTOR, INVERSE() EL VALOR RETORNADO
// DE ESTA SUBRUTINA.
VEC2B PERPENDICULAR(VEC2B V){
	if(ISEQUAL(V  , V2B_ZERO)) return V2B_UNDEF;
	if(ISEQUAL(V.Y, BF_ZERO )) return V2B_DOWN ;
	if(ISEQUAL(V.X, BF_ZERO )) return V2B_RIGHT;
	VEC2B R;
	BINFIX P1,P2;
	P1 = DIV(V.Y, V.X);
	P2 = DIV(BF_NEGONE, P1);
	R.X = BF_ONE;
	R.Y = P1;
	return V;
}

// OBTENER EL ANGULO CON RESPECTO A X-AXIS POSITIVE
BINFIX GET_ANGLE(VEC2B V){
	BINFIX R;
	R = ATAN2(V.Y, V.X);
	return R;
}

VEC2B DECOMPOSE(BINFIX ANGLE){
	VEC2B V;
	V.X = COS(ANGLE);
	V.Y = SIN(ANGLE);
	return V;
}

VEC2B ROTATE(VEC2B V, BINFIX ANGLE){
	VEC2B R;
	// TO POLAR COORDS
	BINFIX A, D;
	D = DIST(V);
	A = ATAN2(V.Y, V.X);
	A = ADD(A, ANGLE);
	// TO CARTESIAN COORDS
	R.X = MUL( COS(A), D);
	R.Y = MUL( SIN(A), D);
	return R;
}

