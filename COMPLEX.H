// COMPLEX ARITHMETIC LIBRARY
// USE BINFIX

struct COMPLEX{
	private:
		BINFIX IM, RE;
	
	public:
		friend COMPLEX MAKECOMPLEX(BINFIX IM, BINFIX RE);
		friend COMPLEX MAKECOMPLEX(BINFIX RE);
		friend BINFIX GET_RE(COMPLEX C);
		friend BINFIX GET_IM(COMPLEX C);
		friend void BREAK(COMPLEX C, BINFIX &RE, BINFIX &IM);
		
		friend COMPLEX ADD(COMPLEX X, COMPLEX Y);
		friend COMPLEX SUB(COMPLEX X, COMPLEX Y);
		friend COMPLEX MUL(COMPLEX X, COMPLEX Y);
		friend COMPLEX DIV(COMPLEX X, COMPLEX Y);
		
		friend BINFIX  MODULE(COMPLEX C);
		friend COMPLEX CONJUGATE(COMPLEX C);
};

COMPLEX MAKECOMPLEX(BINFIX IM, BINFIX RE){
	COMPLEX C;
	C.IM = IM;
	C.RE = RE;
	return C;
}

COMPLEX MAKECOMPLEX(BINFIX RE){
	COMPLEX C;
	C.RE = RE;
	C.IM = BF_ZERO;
	return C;
}

BINFIX GET_RE(COMPLEX C){
	return C.RE;
}

BINFIX GET_IM(COMPLEX C){
	return C.IM;
}

void BREAK(COMPLEX C, BINFIX &RE, BINFIX &IM){
	RE = C.RE;
	IM = C.IM;
}

COMPLEX ADD(COMPLEX X, COMPLEX Y){
	COMPLEX C;
	C.RE = ADD(X.RE, Y.RE);
	C.IM = ADD(X.IM, Y.IM);
	return C;
}

COMPLEX SUB(COMPLEX X, COMPLEX Y){
	COMPLEX C;
	C.RE = SUB(X.RE, Y.RE);
	C.IM = SUB(X.IM, Y.IM);
	return C;
}

COMPLEX MUL(COMPLEX X, COMPLEX Y){
	COMPLEX C;
	C.RE = SUB( MUL(X.RE,Y.RE), MUL(X.IM,Y.IM) );
	C.IM = ADD( MUL(X.RE,Y.IM), MUL(Y.RE,X.IM) );
	return C;
}

COMPLEX DIV(COMPLEX X, COMPLEX Y){
	COMPLEX C;
	BINFIX INVDEN;
	INVDEN = ADD( SQ(Y.RE), SQ(Y.IM) );
	INVDEN = INV(INVDEN);
	C.RE = ADD( MUL(X.RE, Y.RE), MUL(X.IM, Y.IM) );
	C.RE = MUL(C.RE, INVDEN);
	C.IM = ADD( MUL(X.RE, Y.IM), MUL(Y.RE,X.IM) );
	C.IM = INVSIGN(C.IM);
	C.IM = MUL(C.IM, INVDEN);
	return C;
}

BINFIX MODULE(COMPLEX C){
	BINFIX B;
	B = HYPOT(C.RE, C.IM);
	return B;
}

COMPLEX CONJUGATE(COMPLEX C){
	C.IM = INVSIGN(C.IM);
	return C;
}
