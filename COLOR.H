// COLOR SUBROUTINES

#define OPACITY_TRANS  0
#define OPACITY_OPAQUE 255

#define COLOR U32

COLOR MAKECOLOR(U8 R, U8 G, U8 B, U8 O = OPACITY_OPAQUE){
	COLOR C;
	C = (O << 24) | (R << 16) | (G << 8) | (B << 0);
	RETURN C;
}

VOID EXTRACT_COLOR(COLOR C, U8 &R, U8 &G, U8 &B){
	R = (C >> 16) & 0xFF;
	G = (C >>  8) & 0xFF;
	B = (C >>  0) & 0xFF;
}

VOID EXTRACT_COLOR(COLOR C, U8 &R, U8 &G, U8 &B, U8 &O){
	O = (C >> 24) & 0xFF;
	R = (C >> 16) & 0xFF;
	G = (C >>  8) & 0xFF;
	B = (C >>  0) & 0xFF;
}

VOID EXTRACT_OPACITY(COLOR C, U8 &O){
	O = (C >> 24) & 0xFF;
}

COLOR COLOR_TINT(COLOR X, COLOR Y){
	COLOR C;
	U8 XR, XG, XB;
	U8 YR, YG, YB;
	U8 CR, CG, CB;
	EXTRACT_COLOR(X, XR, XG, XB);
	EXTRACT_COLOR(Y, YR, YG, YB);
	
	CR = (XR + YR) / 2;
	CG = (XG + YG) / 2;
	CB = (XB + YB) / 2;
	
	C = MAKECOLOR(CR, CG, CB);
	RETURN C;
}

COLOR COLOR_INVERSE(COLOR X){
	COLOR C;
	U8 XR, XG, XB;
	U8 CR, CG, CB;
	EXTRACT_COLOR(X, XR, XG, XB);
	
	CR = 255 - XR;
	CG = 255 - XG;
	CB = 255 - XB;
	
	C = MAKECOLOR(CR, CG, CB);
	RETURN C;
}

// TINTED WITH OPACITY
// X HAS OPACITY, Y IS FULL OPAQUE
// IF WE DIVIDE BY 256 INSTEAD OF 255, THE MAXIMUM ERROR IS 1.
COLOR COLOR_OTINT(COLOR X, COLOR Y){
	COLOR C;
	U8 XR, XG, XB, XO;
	U8 CR, CG, CB;
	U8 YR, YG, YB;
	EXTRACT_COLOR(X, XR, XG, XB, XO);
	EXTRACT_COLOR(Y, YR, YG, YB);
	
	CR = (INT((F32(XR) * F32(XO)) * F32_INV255) + YR) / 2;
	CG = (INT((F32(XG) * F32(XO)) * F32_INV255) + YG) / 2;
	CB = (INT((F32(XB) * F32(XO)) * F32_INV255) + YB) / 2;
	
	C = MAKECOLOR(CR, CG, CB);
	RETURN C;
}

